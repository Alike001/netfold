import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const artifactPath = resolve(root, "contracts/out/NetFoldClearing.sol/NetFoldClearing.json");
const destination = resolve(root, "lib/generated/netfold-clearing-abi.ts");
const artifact = JSON.parse(await readFile(artifactPath, "utf8"));

if (!Array.isArray(artifact.abi)) throw new Error(`Foundry artifact has no ABI: ${artifactPath}`);

const output = `// Generated by scripts/sync-netfold-abi.mjs from the committed contract source build.\n// Do not edit by hand. Regenerate after an intentional contract ABI change.\nexport const netFoldAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
await mkdir(dirname(destination), { recursive: true });
await writeFile(destination, output);
console.log(`Wrote ${artifact.abi.length} ABI entries to ${destination}`);
